// Copies compiled ABIs from contracts/out into the app (as `as const` TS for viem types).
import { readFileSync, writeFileSync, mkdirSync } from "node:fs";
import { join, dirname } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const outDir = join(root, "app/src/server/abi");
mkdirSync(outDir, { recursive: true });

const items = [
  ["AnyCheckoutVault", "AnyCheckoutVault.sol"],
  ["LocalForwarder", "LocalForwarder.sol"],
  ["MockUSDC", "MockUSDC.sol"],
  ["MockMessageTransmitterV2", "MockMessageTransmitterV2.sol"],
];
for (const [name, file] of items) {
  const art = JSON.parse(readFileSync(join(root, "contracts/out", file, `${name}.json`), "utf8"));
  const ts = `// Generated by scripts/export-abi.mjs from contracts/out. Do not edit.\nexport const ${name}Abi = ${JSON.stringify(art.abi, null, 2)} as const;\n`;
  writeFileSync(join(outDir, `${name}.ts`), ts);
  console.log("wrote", name);
}
